-- Schema inicial. IF NOT EXISTS permite reaplicação sem apagar dados;
-- alterações futuras de tabelas existentes deverão usar migrations explícitas.
CREATE TABLE IF NOT EXISTS public.usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    slug TEXT NOT NULL UNIQUE CHECK (btrim(slug) <> ''),
    nome TEXT NOT NULL CHECK (btrim(nome) <> ''),
    sobrenome TEXT NOT NULL CHECK (btrim(sobrenome) <> ''),
    email TEXT CHECK (email IS NULL OR (email = btrim(email) AND email <> '')),
    telefone TEXT UNIQUE CHECK (telefone IS NULL OR telefone ~ '^[0-9]{8,}$'),
    idade SMALLINT NOT NULL CHECK (idade BETWEEN 10 AND 120),
    genero TEXT NOT NULL CHECK (btrim(genero) <> ''),
    colaborador BOOLEAN NOT NULL DEFAULT FALSE,
    administrador BOOLEAN NOT NULL DEFAULT FALSE,
    pontos INTEGER NOT NULL DEFAULT 0 CHECK (pontos >= 0),
    bio TEXT NOT NULL DEFAULT '',
    localizacao TEXT NOT NULL DEFAULT 'Brasil',
    disponivel_atendimento BOOLEAN NOT NULL DEFAULT FALSE,
    senha_hash TEXT NOT NULL CHECK (btrim(senha_hash) <> ''),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuarios_contato_check CHECK (email IS NOT NULL OR telefone IS NOT NULL),
    CONSTRAINT usuarios_disponibilidade_check CHECK (NOT disponivel_atendimento OR colaborador)
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_unique ON public.usuarios (lower(email));

CREATE TABLE IF NOT EXISTS public.categorias (
    id TEXT PRIMARY KEY CHECK (btrim(id) <> ''),
    nome TEXT NOT NULL CHECK (btrim(nome) <> '')
);

CREATE TABLE IF NOT EXISTS public.tutoriais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    slug TEXT NOT NULL UNIQUE CHECK (btrim(slug) <> ''),
    autor_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    categoria_id TEXT NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
    titulo TEXT NOT NULL CHECK (char_length(btrim(titulo)) BETWEEN 8 AND 160),
    resumo TEXT NOT NULL CHECK (char_length(btrim(resumo)) BETWEEN 15 AND 320),
    conteudo TEXT NOT NULL CHECK (char_length(btrim(conteudo)) BETWEEN 30 AND 6000),
    video_url TEXT CHECK (video_url IS NULL OR btrim(video_url) <> ''),
    visualizacoes INTEGER NOT NULL DEFAULT 0 CHECK (visualizacoes >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.tutorial_passos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    tutorial_id INTEGER NOT NULL REFERENCES public.tutoriais(id) ON DELETE CASCADE,
    ordem SMALLINT NOT NULL CHECK (ordem BETWEEN 1 AND 9),
    titulo TEXT NOT NULL CHECK (char_length(btrim(titulo)) BETWEEN 3 AND 120),
    descricao TEXT NOT NULL CHECK (char_length(btrim(descricao)) BETWEEN 3 AND 1000),
    imagem_url TEXT CHECK (imagem_url IS NULL OR btrim(imagem_url) <> ''),
    imagem_alt TEXT CHECK (imagem_alt IS NULL OR char_length(imagem_alt) BETWEEN 1 AND 180),
    imagem_legenda TEXT CHECK (imagem_legenda IS NULL OR char_length(imagem_legenda) <= 240),
    link_url TEXT CHECK (link_url IS NULL OR char_length(btrim(link_url)) BETWEEN 1 AND 2048),
    link_texto TEXT CHECK (link_texto IS NULL OR char_length(btrim(link_texto)) BETWEEN 1 AND 120),
    UNIQUE (tutorial_id, ordem),
    CONSTRAINT tutorial_passos_imagem_check CHECK (
        (imagem_url IS NULL AND imagem_alt IS NULL AND imagem_legenda IS NULL)
        OR (imagem_url IS NOT NULL AND imagem_alt IS NOT NULL)
    ),
    CONSTRAINT tutorial_passos_link_check CHECK ((link_url IS NULL) = (link_texto IS NULL))
);

CREATE TABLE IF NOT EXISTS public.tutorial_tags (
    tutorial_id INTEGER NOT NULL REFERENCES public.tutoriais(id) ON DELETE CASCADE,
    tag TEXT NOT NULL CHECK (char_length(btrim(tag)) BETWEEN 1 AND 40),
    PRIMARY KEY (tutorial_id, tag)
);

CREATE TABLE IF NOT EXISTS public.comentarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    tutorial_id INTEGER NOT NULL REFERENCES public.tutoriais(id) ON DELETE CASCADE,
    usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    texto TEXT NOT NULL CHECK (char_length(btrim(texto)) BETWEEN 2 AND 1000),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.avaliacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    tutorial_id INTEGER NOT NULL REFERENCES public.tutoriais(id) ON DELETE CASCADE,
    avaliador_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    nota SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ,
    UNIQUE (tutorial_id, avaliador_id)
);

-- PKs/UNIQUE compostas já cobrem o primeiro campo: passos,
-- tags e avaliações dispensam índices adicionais pelo mesmo tutorial/usuário.
CREATE INDEX IF NOT EXISTS idx_tutoriais_autor_id ON public.tutoriais (autor_id);
CREATE INDEX IF NOT EXISTS idx_tutoriais_categoria_id ON public.tutoriais (categoria_id);
CREATE INDEX IF NOT EXISTS idx_comentarios_tutorial_id ON public.comentarios (tutorial_id);
CREATE INDEX IF NOT EXISTS idx_comentarios_usuario_id ON public.comentarios (usuario_id);
CREATE INDEX IF NOT EXISTS idx_avaliacoes_avaliador_id ON public.avaliacoes (avaliador_id);
