function normalizarTexto(
    valor = ''
) {

    return String(valor)

        .normalize(
            'NFD'
        )

        .replace(
            /[\u0300-\u036f]/g,
            ''
        )

        .toLowerCase()

        .trim();

}


function criarSlugBase(
    valor = ''
) {

    return normalizarTexto(
        valor
    )

        .replace(
            /[^a-z0-9]+/g,
            '-'
        )

        .replace(
            /^-+|-+$/g,
            ''
        );

}


function criarSlugUnico(
    titulo
) {

    const base =
        criarSlugBase(
            titulo
        )
        || 'tutorial';


    let slug =
        base;


    let sufixo =
        2;


    while (
        tutoriais.some(
            tutorial =>
                tutorial.slug
                === slug
        )
    ) {

        slug =
            `${base}-${sufixo}`;

        sufixo +=
            1;

    }


    return slug;

}


function proximoId() {

    if (
        tutoriais.length
        === 0
    ) {

        return 1;

    }


    return (
        Math.max(
            ...tutoriais.map(
                tutorial =>
                    tutorial.id
            )
        )
        +
        1
    );

}


function findAll() {

    return [
        ...tutoriais
    ]

        .sort(
            (a, b) =>

                new Date(
                    b.criadoEm
                )

                -

                new Date(
                    a.criadoEm
                )
        );

}


function findById(id) {

    const numero =
        Number(id);


    return (
        tutoriais.find(
            tutorial =>
                tutorial.id
                === numero
        )
        ||
        null
    );

}


function findBySlug(
    slug
) {

    return (
        tutoriais.find(
            tutorial =>
                tutorial.slug
                === String(slug)
        )
        ||
        null
    );

}


function findByAutorId(
    autorId
) {

    const numero =
        Number(
            autorId
        );


    return tutoriais

        .filter(
            tutorial =>
                tutorial.autorId
                === numero
        )

        .sort(
            (a, b) =>

                new Date(
                    b.criadoEm
                )

                -

                new Date(
                    a.criadoEm
                )
        );

}


